/**
 * KAN-110 review (comment 10539): regressions for the Proposal A (Jest + Yarn) estimate.
 * deps-plan.sh stops at the first problem: with no package-lock.json it never looks at workspaces,
 * root lifecycle scripts or git/file/link dependencies. The first estimate treated "add Yarn" as if
 * it cleared every dependency blocker. Each case below must stay blocked or unknown under a
 * HYPOTHETICAL Yarn + Jest adapter unless that restriction is separately supported.
 * The audit is static: it parses files; it never runs Yarn, plugins or repository code.
 */
const { test, describe } = require('node:test');
const assert = require('node:assert/strict');
const path = require('path');

const PUB = path.join(__dirname, '..', '..', 'bench', 'public');
const load = (m) => import(path.join(PUB, m));

const CLASSIC = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


jest@^29.0.0:
  version "29.7.0"
  resolved "https://registry.yarnpkg.com/jest/-/jest-29.7.0.tgz#abc"
  integrity sha512-AAAA

left-pad@^1.3.0:
  version "1.3.0"
  resolved "https://registry.npmjs.org/left-pad/-/left-pad-1.3.0.tgz#def"
  integrity sha512-BBBB
`;
const BERRY = `__metadata:
  version: 6
  cacheKey: 8

"jest@npm:^29.0.0":
  version: 29.7.0
  resolution: "jest@npm:29.7.0"
  checksum: 1234abcd
  languageName: node
  linkType: hard
`;
const pkg = (extra = {}) => ({ name: 'x', scripts: { test: 'jest' }, devDependencies: { jest: '^29.0.0' }, ...extra });
const task = (deps, extra = {}) => ({
  runner_frameworks: ['jest'], grader_evidence: 'present', services: [], node: { engines: '>=20' }, ...extra, deps,
});

describe('KAN-110 review: Yarn audit checks every restriction, not just the first', () => {
  test('classic and berry generations are recognised; garbage is unreadable, not "ready"', async () => {
    const { yarnGeneration } = await load('proposal-a.mjs');
    assert.equal(yarnGeneration(CLASSIC).generation, 'classic');
    assert.deepEqual(yarnGeneration(BERRY), { generation: 'berry', metadata_version: 6 });
    assert.equal(yarnGeneration('not a lockfile').generation, null);
  });

  test('a clean classic project passes the audit', async () => {
    const { auditYarn } = await load('proposal-a.mjs');
    const a = auditYarn({ pkg: pkg(), lockText: CLASSIC, rootFiles: new Set(['package.json', 'yarn.lock']) });
    assert.deepEqual(a.blockers, []);
    assert.equal(a.generation, 'classic');
    assert.match(a.lock_sha256, /^[0-9a-f]{64}$/);
    assert.deepEqual(a.registries.sort(), ['registry.npmjs.org', 'registry.yarnpkg.com']);
    assert.ok(a.requirements.includes('yarn:registry-mapping'), 'registry.yarnpkg.com needs an explicit mapping to the npm registry');
  });

  test('Yarn-only + workspaces stays blocked', async () => {
    const { auditYarn } = await load('proposal-a.mjs');
    assert.ok(auditYarn({ pkg: pkg({ workspaces: ['packages/*'] }), lockText: CLASSIC, rootFiles: new Set(['yarn.lock']) }).blockers.includes('deps:workspaces'));
  });

  test('Yarn-only + root prepare/install script stays blocked', async () => {
    const { auditYarn } = await load('proposal-a.mjs');
    for (const s of ['prepare', 'install', 'postinstall', 'preinstall']) {
      const a = auditYarn({ pkg: pkg({ scripts: { test: 'jest', [s]: 'node build.js' } }), lockText: CLASSIC, rootFiles: new Set(['yarn.lock']) });
      assert.ok(a.blockers.includes('deps:lifecycle-scripts'), s);
    }
  });

  test('Yarn-only + git/file/link dependency stays blocked (lockfile or manifest)', async () => {
    const { auditYarn } = await load('proposal-a.mjs');
    const gitLock = CLASSIC + '\nfoo@git+https://github.com/a/foo.git:\n  version "1.0.0"\n  resolved "git+https://github.com/a/foo.git#0123456"\n';
    assert.ok(auditYarn({ pkg: pkg(), lockText: gitLock, rootFiles: new Set(['yarn.lock']) }).blockers.includes('deps:git-or-file-deps'));
    for (const spec of ['file:../local', 'link:./x', 'github:a/b', 'git+ssh://git@github.com/a/b.git', 'portal:./p']) {
      const a = auditYarn({ pkg: pkg({ dependencies: { local: spec } }), lockText: CLASSIC, rootFiles: new Set(['yarn.lock']) });
      assert.ok(a.blockers.includes('deps:git-or-file-deps'), spec);
    }
  });

  test('missing yarn.lock is blocked; an unreadable one is unknown', async () => {
    const { auditYarn } = await load('proposal-a.mjs');
    assert.ok(auditYarn({ pkg: pkg(), lockText: null, rootFiles: new Set(['package.json']) }).blockers.includes('yarn:missing-lockfile'));
    const bad = auditYarn({ pkg: pkg(), lockText: '<<<<<<< merge conflict', rootFiles: new Set(['yarn.lock']) });
    assert.ok(bad.unknowns.includes('yarn:unreadable-lockfile'));
    assert.ok(!bad.blockers.length || !bad.blockers.includes('none'));
  });

  test('missing integrity/checksum is blocked (no verifiable immutable install)', async () => {
    const { auditYarn } = await load('proposal-a.mjs');
    const noInt = CLASSIC.replace(/\n  integrity sha512-BBBB/, '');
    assert.ok(auditYarn({ pkg: pkg(), lockText: noInt, rootFiles: new Set(['yarn.lock']) }).blockers.includes('yarn:missing-integrity'));
  });

  test('repository-supplied Yarn binary or plugins are blocked (would execute repository code)', async () => {
    const { auditYarn } = await load('proposal-a.mjs');
    const a = auditYarn({ pkg: pkg(), lockText: BERRY, yarnrcYml: 'yarnPath: .yarn/releases/yarn-3.6.0.cjs\nplugins:\n  - path: .yarn/plugins/@yarnpkg/plugin-workspace-tools.cjs\n', rootFiles: new Set(['yarn.lock', '.yarnrc.yml']) });
    assert.ok(a.blockers.includes('yarn:repo-supplied-binary-or-plugins'));
    const c = auditYarn({ pkg: pkg(), lockText: CLASSIC, yarnrc: 'yarn-path ".yarn/releases/yarn-1.22.19.js"\n', rootFiles: new Set(['yarn.lock', '.yarnrc']) });
    assert.ok(c.blockers.includes('yarn:repo-supplied-binary-or-plugins'));
  });

  test('GitHub tarballs are git dependencies; a sha1 URL fragment is a weaker hash, not a missing one', async () => {
    const { auditYarn } = await load('proposal-a.mjs');
    const gh = CLASSIC + '\nfoo@https://codeload.github.com/a/foo/tar.gz/0123456:\n  version "1.0.0"\n  resolved "https://codeload.github.com/a/foo/tar.gz/0123456"\n';
    const a = auditYarn({ pkg: pkg(), lockText: gh, rootFiles: new Set(['yarn.lock']) });
    assert.ok(a.blockers.includes('deps:git-or-file-deps'));
    assert.ok(!a.blockers.includes('deps:non-npm-registry'));
    const sha1 = CLASSIC.replace(/\n  integrity sha512-[AB]+/g, '').replace('#abc', '#' + 'a'.repeat(40)).replace('#def', '#' + 'b'.repeat(40));
    const b = auditYarn({ pkg: pkg(), lockText: sha1, rootFiles: new Set(['yarn.lock']) });
    assert.ok(!b.blockers.includes('yarn:missing-integrity'), JSON.stringify(b.blockers));
    assert.ok(b.requirements.includes('yarn:sha1-only-integrity'));
  });

  test('a registry other than npm (or its yarnpkg mirror) is blocked', async () => {
    const { auditYarn } = await load('proposal-a.mjs');
    const priv = CLASSIC.replace('https://registry.npmjs.org/left-pad', 'https://npm.example.com/left-pad');
    assert.ok(auditYarn({ pkg: pkg(), lockText: priv, rootFiles: new Set(['yarn.lock']) }).blockers.includes('deps:non-npm-registry'));
    const rc = auditYarn({ pkg: pkg(), lockText: CLASSIC, yarnrc: 'registry "https://npm.example.com/"\n', rootFiles: new Set(['yarn.lock', '.yarnrc']) });
    assert.ok(rc.blockers.includes('deps:non-npm-registry'));
  });
});

describe('KAN-110 review: Proposal A classification', () => {
  test('unsupported Yarn generation stays blocked', async () => {
    const { auditYarn, proposalA } = await load('proposal-a.mjs');
    const deps = auditYarn({ pkg: pkg(), lockText: BERRY, rootFiles: new Set(['yarn.lock']) });
    const r = proposalA(task(deps), { yarn: ['classic'] });
    assert.equal(r.status, 'incompatible');
    assert.ok(r.blockers.includes('yarn:unsupported-generation:berry'));
  });

  test('missing grader evidence is unknown, never eligible', async () => {
    const { auditYarn, proposalA } = await load('proposal-a.mjs');
    const deps = auditYarn({ pkg: pkg(), lockText: CLASSIC, rootFiles: new Set(['yarn.lock']) });
    const r = proposalA(task(deps, { grader_evidence: 'missing' }), { yarn: ['classic'] });
    assert.equal(r.status, 'unknown');
    assert.ok(r.unknowns.includes('grader:evidence-missing'));
  });

  test('no declared Node version is unknown; Node < 20 is incompatible; a hint is never execution proof', async () => {
    const { auditYarn, proposalA } = await load('proposal-a.mjs');
    const deps = auditYarn({ pkg: pkg(), lockText: CLASSIC, rootFiles: new Set(['yarn.lock']) });
    assert.ok(proposalA(task(deps, { node: {} }), { yarn: ['classic'] }).unknowns.includes('runtime:undeclared'));
    // A pinned old Node (.nvmrc / setup image) is a hint, not proof: unknown on Node 24, not incompatible
    const pinned = proposalA(task(deps, { node: { nvmrc: '16.3.0' } }), { yarn: ['classic'] });
    assert.ok(pinned.unknowns.includes('runtime:pinned-node16'), JSON.stringify(pinned));
    assert.ok(!pinned.blockers.some((b) => b.startsWith('runtime')));
    // A declared engines range that excludes Node 24 blocks; a minimum such as >=14 admits it
    assert.ok(proposalA(task(deps, { node: { engines: '>=10.9.0 <13.0.0' } }), { yarn: ['classic'] }).blockers.includes('runtime:engines-exclude-node24'));
    assert.ok(proposalA(task(deps, { node: { engines: '16' } }), { yarn: ['classic'] }).blockers.includes('runtime:engines-exclude-node24'));
    assert.ok(!proposalA(task(deps, { node: { engines: '>=14' } }), { yarn: ['classic'] }).blockers.some((b) => b.startsWith('runtime')));
    const { rangeAdmits } = await load('proposal-a.mjs');
    for (const r of ['>=8.0.0', '>= 8', '>= v18.16.0', '>=20.0.0', '>=4', '^14 || >=20', '*']) assert.equal(rangeAdmits(r, 24), true, r);
    for (const r of ['16', '>= 12 <= 14', '>=10.9.0 <13.0.0', '^14 || ^16', '14.x', '<20']) assert.equal(rangeAdmits(r, 24), false, r);
    // yarn.lock does not record install scripts: without them from another source, the task stays unknown
    assert.ok(proposalA(task(deps), { yarn: ['classic'] }).unknowns.includes('install:dependency-scripts-unrecorded'));
    const known = auditYarn({ pkg: pkg(), lockText: CLASSIC, rootFiles: new Set(['yarn.lock']), installScripts: { required: [], optional: [] } });
    const ok = proposalA(task(known), { yarn: ['classic'] });
    assert.equal(ok.status, 'eligible_static');
    assert.ok(ok.conditions.includes('runtime:unverified'), 'eligible is static: runtime is still unverified');
  });

  test('other runners and services stay blocked; Jest is the only runner Proposal A adds', async () => {
    const { auditYarn, proposalA } = await load('proposal-a.mjs');
    const deps = auditYarn({ pkg: pkg(), lockText: CLASSIC, rootFiles: new Set(['yarn.lock']) });
    assert.ok(proposalA(task(deps, { runner_frameworks: ['jest', 'karma'] }), { yarn: ['classic'] }).blockers.includes('runner:karma'));
    assert.ok(proposalA(task(deps, { runner_frameworks: [] }), { yarn: ['classic'] }).unknowns.includes('runner:unidentified'));
    assert.ok(proposalA(task(deps, { services: ['xvfb'] }), { yarn: ['classic'] }).blockers.includes('service:xvfb'));
  });

  test('native addons with install scripts are unknown in a compiler-less sandbox', async () => {
    const { auditNpm, proposalA } = await load('proposal-a.mjs');
    const lock = { lockfileVersion: 2, packages: { '': {}, 'node_modules/microtime': { version: '3.0.0', hasInstallScript: true, integrity: 'sha512-x', resolved: 'https://registry.npmjs.org/microtime/-/microtime-3.0.0.tgz' }, 'node_modules/fsevents': { version: '2.3.2', optional: true, hasInstallScript: true, integrity: 'sha512-y', resolved: 'https://registry.npmjs.org/fsevents/-/fsevents-2.3.2.tgz' } } };
    const deps = auditNpm({ pkg: pkg(), lock });
    assert.deepEqual(deps.blockers, []);
    assert.deepEqual(deps.install_scripts, { required: ['microtime'], optional: ['fsevents'] });
    const r = proposalA(task(deps), { yarn: ['classic'] });
    assert.equal(r.status, 'unknown');
    assert.ok(r.unknowns.includes('install:native-or-script-deps:microtime'));
  });

  test('npm audit reports every restriction at once, not only the first', async () => {
    const { auditNpm } = await load('proposal-a.mjs');
    const lock = { lockfileVersion: 1, dependencies: {} };
    const a = auditNpm({ pkg: pkg({ workspaces: ['p/*'], scripts: { test: 'jest', prepare: 'x' } }), lock });
    for (const b of ['deps:npm-lockfile-v1', 'deps:workspaces', 'deps:lifecycle-scripts']) assert.ok(a.blockers.includes(b), b);
  });

  test('the first estimate\'s bug: adapters.mjs no longer clears workspaces for Yarn-only projects', async () => {
    const { blockers } = await load('adapters.mjs');
    const t = { facts: { qb_detected_runner: 'jest', runner_from_scripts: { frameworks: ['jest'] }, runner_from_grader: ['jest'], workspaces: true,
      qb_deps_plan: { status: 'blocked', reason: 'setup_missing_lockfile' }, package_manager: { lockfiles: ['yarn'] }, qb_test_plan: { status: 'not_run' }, services: [], node: {} } };
    assert.ok(blockers(t).has('deps:workspaces'));
  });
});

describe('KAN-110 review 10541: bounded profile labels', () => {
  test('only validated Jest versions count; others are unknown, never eligible', async () => {
    const { auditNpm, proposalA } = await load('proposal-a.mjs');
    const lock = { lockfileVersion: 2, packages: { '': {}, 'node_modules/jest': { version: '29.6.4', integrity: 'sha512-x', resolved: 'https://registry.npmjs.org/jest/-/jest-29.6.4.tgz' } } };
    const deps = auditNpm({ pkg: pkg(), lock });
    const ok = proposalA({ ...task(deps), jest_version: '29.6.4' }, { yarn: [], jestVersions: ['29.6.4'] });
    assert.equal(ok.status, 'eligible_static');
    const other = proposalA({ ...task(deps), jest_version: '28.1.0' }, { yarn: [], jestVersions: ['29.6.4'] });
    assert.equal(other.status, 'unknown');
    assert.ok(other.unknowns.includes('runner:jest-version-unvalidated:28.1.0'));
  });

  test('with Yarn deferred, a Yarn Classic project is blocked; conditionalOn lists the extra work instead of "eligible"', async () => {
    const { auditYarn, proposalA, conditionalOn } = await load('proposal-a.mjs');
    const deps = auditYarn({ pkg: pkg(), lockText: CLASSIC.replace(/\n  integrity sha512-[AB]+/g, '').replace('#abc', '#' + 'a'.repeat(40)).replace('#def', '#' + 'b'.repeat(40)), rootFiles: new Set(['yarn.lock']), installScripts: { required: [], optional: [] } });
    const bounded = proposalA({ ...task(deps), jest_version: '18.0.0' }, { yarn: [], jestVersions: ['27.2.0', '29.6.4'] });
    assert.equal(bounded.status, 'incompatible');
    assert.ok(bounded.blockers.includes('yarn:deferred'));
    const extended = proposalA({ ...task(deps), jest_version: '18.0.0' }, { yarn: ['classic'] });
    assert.deepEqual(conditionalOn(extended, { jest_version: '18.0.0', validated: ['27.2.0', '29.6.4'] }).sort(),
      ['integrity:sha1-only', 'jest:legacy-18.0.0', 'registry:yarnpkg-mapping', 'runtime:unverified', 'yarn:classic-support']);
  });
});
