#!/usr/bin/env node
// Renders the field dictionary (public/FIELDS.md) from field-policy.mjs, so the two cannot drift.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { POLICY } from './field-policy.mjs';
const HERE = path.dirname(fileURLToPath(import.meta.url));
const SRC = JSON.parse(fs.readFileSync(path.join(HERE, 'sources.json'), 'utf8')).sources;
let md = '# KAN-110 field dictionary\n\nGenerated by `node public/dictionary.mjs` from `field-policy.mjs`. Do not edit by hand.\n\n';
md += 'Every source column belongs to exactly one store:\n\n| Store | Who sees it |\n|---|---|\n| **agent** | Both arms (the agent packet), after leak redaction. |\n| **controller** | The run controller only: sets up the clean base repository and environment. |\n| **vault** | The grader only: reference solution, hidden tests, test lists, grading commands. |\n| **quarantine** | Nobody during a run: hints, solution size/shape, difficulty labels from historical model results, answer-bearing IDs kept for provenance. |\n\nA column that is not listed here is quarantined automatically.\n\n';
for (const [src, cols] of Object.entries(POLICY)) {
  const s = SRC.find((x) => x.source === src);
  md += `## ${src}\n\n\`${s.hf_dataset}\` at \`${s.revision}\`\n\n| Column | Store | Why |\n|---|---|---|\n`;
  for (const [c, [cls, why]] of Object.entries(cols)) md += `| \`${c}\` | ${cls} | ${why} |\n`;
  md += '\n';
}
fs.writeFileSync(path.join(HERE, 'FIELDS.md'), md);
console.log('wrote public/FIELDS.md');
